"""Regenerate the decision and working-folder indexes from frontmatter.

    uv run records/reindex.py           # write both indexes
    uv run records/reindex.py --check   # exit 1 if either is stale

Reads   <records>/<decisions>/*.md and <records>/work/*/README.md (+ work/archive/YYYY/*/)
Writes  <records>/<decisions>/index.md and <records>/work/index.md — never hand-edit them.
<records> is the folder this script lives in. A missing folder is skipped, not an error.
"""

from pathlib import Path
import sys

BANNER = "<!-- GENERATED by reindex.py — do not edit by hand. -->"
DECISION_DIRS = ["decisions", "Decisions", "adr", "ADR"]
NOT_RECORDS = {"index.md", "readme.md", "0000-template.md"}
# Older folders used other words; the name stays, the index shows the current vocabulary.
TYPE_ALIASES = {"symptom": "problem", "bug": "problem", "defect": "problem",
                "feature": "change", "request": "change", "enhancement": "change"}
STATUS_ALIASES = {"landed": "done"}


def frontmatter(path):
    """Flat `key: value` pairs and `[a, b]` lists; `# comments` stripped. None if absent."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    data = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return data
        line = line.split(" #", 1)[0].strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
        else:
            value = value.strip("\"'")
        data[key.strip()] = value
    return None  # unterminated


def cell(value):
    if isinstance(value, list):
        value = ", ".join(value)
    return str(value).replace("|", "\\|") if value else "—"


def document(heading, headers, rows, noun):
    table = "_Nothing recorded yet._" if not rows else "\n".join(
        ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
        + ["| " + " | ".join(r) + " |" for r in rows])
    return f"{BANNER}\n\n# {heading}\n\n{table}\n\n_{len(rows)} {noun}._\n"


def decision_index(folder):
    rows = []
    for path in sorted(folder.glob("*.md")):
        if path.name.lower() in NOT_RECORDS:
            continue
        fm = frontmatter(path)
        if fm is None:
            print(f"  ! no frontmatter, skipped: {path.name}", file=sys.stderr)
            continue
        # `0007-title.md` or older `ADR-0007-title.md`
        number = (fm.get("number") or fm.get("adr")
                  or next((p for p in path.stem.split("-") if p.isdigit()), path.stem))
        rows.append((str(number), [f"[{number}]({path.name})", cell(fm.get("title")),
                                   cell(fm.get("status")), cell(fm.get("date")),
                                   cell(fm.get("source"))]))
    rows.sort(key=lambda r: r[0])
    return document("Decision records", ["#", "Title", "Status", "Date", "Source"],
                    [r for _, r in rows], "record(s)")


def work_index(work):
    folders = [p for p in work.iterdir() if p.is_dir() and p.name != "archive"]
    archive = work / "archive"
    if archive.is_dir():
        folders += [p for year in archive.iterdir() if year.is_dir()
                    for p in year.iterdir() if p.is_dir()]
    rows = []
    for folder in sorted(folders, key=lambda p: p.name, reverse=True):
        readme = folder / "README.md"
        fm = frontmatter(readme) if readme.is_file() else None
        if fm is None:
            print(f"  ! no README frontmatter, skipped: {folder.name}", file=sys.stderr)
            continue
        kind = fm.get("type", "")
        status = fm.get("status", "")
        rel = folder.relative_to(work).as_posix()
        rows.append([f"[{folder.name}]({rel}/README.md)",
                     cell(TYPE_ALIASES.get(kind, kind)),
                     cell(STATUS_ALIASES.get(status, status)),
                     cell(fm.get("started")), cell(fm.get("branch")),
                     cell(fm.get("decisions") or fm.get("adrs"))])
    return document("Working folders",
                    ["Folder", "Type", "Status", "Started", "Branch", "Decisions"],
                    rows, "folder(s)")


def emit(path, content, check):
    """Write content, or in check mode report. Returns True if the file was stale."""
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if current == content:
        print(f"{path.name}: up to date")
        return False
    if not check:
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{path.parent.name}/{path.name}: {'STALE' if check else 'written'}")
    return True


def main(argv=None, records=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    records = records or Path(__file__).resolve().parent
    stale = False
    decisions = next((records / d for d in DECISION_DIRS if (records / d).is_dir()), None)
    if decisions:
        stale |= emit(decisions / "index.md", decision_index(decisions), check)
    if (records / "work").is_dir():
        stale |= emit(records / "work" / "index.md", work_index(records / "work"), check)
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
